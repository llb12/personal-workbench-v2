'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { activate, validateProfile } = require('../pilot-runtime');
const profile = fs.mkdtempSync(path.join(__dirname, '../.integration-evidence/pilot-guard-'));
const app = new EventEmitter();
app.getPath = key => key === 'appData' ? process.env.APPDATA : profile;
app.commandLine = { hasSwitch: key => key === 'user-data-dir', getSwitchValue: () => profile };
assert.throws(() => validateProfile({ ...app, commandLine: { hasSwitch: () => false } }), /EXPLICIT_PROFILE_REQUIRED/);
fs.writeFileSync(path.join(profile, 'profile-marker.json'), JSON.stringify({ kind: 'personal-workbench-isolated-pilot-v1', expectedUserData: profile }));
const pilot = activate(app, {});
assert.throws(() => fs.readFileSync(path.join(process.env.APPDATA, 'personal-workbench-optimized', 'never-opened.json')), /FORMAL_ACCESS_BLOCKED/);
assert.throws(() => fs.writeFileSync(path.join(profile, '..', 'never-created.txt'), 'blocked'), /WRITE_OUTSIDE_PROFILE_BLOCKED/);
fs.writeFileSync(path.join(profile, 'synthetic.txt'), 'Synthetic content');
assert.equal(fs.readFileSync(path.join(profile, 'synthetic.txt'), 'utf8'), 'Synthetic content');
assert.equal(pilot.audit.formalAccessBlocked, 1);
assert.equal(pilot.audit.writesOutsideProfileBlocked, 1);
assert.equal(pilot.active, true);
pilot.persist();
console.log('PILOT_GUARD_PASS: marked explicit profile required; formal access and external writes rejected before filesystem calls');

'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const html = fs.readFileSync(path.join(__dirname, '../index.html'), 'utf8');
const nodes = {};
for (const id of ['main', 'aiDrawer', 'aiDrawerMask', 'taskModalMask', 'wbConfirmMask']) nodes[id] = { id, inert: false, contains(el) { return this === el; } };
let escape;
const context = { Map, $: id => nodes[id], document: { body: { children: Object.values(nodes) }, addEventListener(type, handler) { if (type === 'keydown') escape = handler; } } };
vm.createContext(context);
const start = html.indexOf('var wbOverlayStack=[];'), end = html.indexOf('/* P0-2A:', start);
vm.runInContext(html.slice(start, end), context);
context.wbOverlayPush('ai-drawer', () => context.wbOverlayDrop('ai-drawer'), () => true);
assert.equal(nodes.main.inert, true); assert.equal(nodes.aiDrawer.inert, false); assert.equal(nodes.aiDrawerMask.inert, false);
context.wbOverlayPush('v2-modal:taskModalMask', () => context.wbOverlayDrop('v2-modal:taskModalMask'), () => true);
assert.equal(nodes.aiDrawer.inert, true); assert.equal(nodes.taskModalMask.inert, false);
escape({ key: 'Escape', preventDefault() {}, stopImmediatePropagation() {} });
assert.equal(nodes.aiDrawer.inert, false); assert.equal(nodes.main.inert, true);
escape({ key: 'Escape', preventDefault() {}, stopImmediatePropagation() {} });
assert.ok(Object.values(nodes).every(node => node.inert === false));
assert.ok(/<button[^>]*id="wxToggle"[^>]*aria-expanded="false"/.test(html));
assert.ok(!/<button[^>]*id="wxToggle"[^]*?<button[^]*?<\/button>[^]*?<\/button>/.test(html.slice(html.indexOf('id="weather"'), html.indexOf('id="weather"') + 650)), 'Weather buttons must be siblings');
console.log('KEYBOARD_OVERLAYS_PASS: native weather trigger, nested modal inert boundaries, topmost Escape and background restoration');

'use strict';
const assert = require('node:assert/strict');
const { createWeatherClient, resolveCity, parseCurrent, parseForecast, observationTime } = require('../weather-client');
const now = Date.parse('2026-10-22T10:20:00Z');
const current = { city: '101010200', cityname: '海淀', temp: '14.4', weather: '阴', SD: '36%', wse: '8km/h', WD: '西南风', WS: '2级', date: '10月22日(星期四)', time: '18:10' };
const raw = 'var dataSK=' + JSON.stringify(current);
const forecast = '<div id="7d"><input id="fc_24h_internal_update_time" value="2026123118"/><ul class="t clearfix">' + [31, 1, 2, 3].map((day, i) => '<li><h1>' + day + '日</h1><p class="wea">多云</p><p class="tem">' + (i ? '<span>17℃</span>/' : '') + '<i>6℃</i></p></li>').join('') + '</ul></div>';
assert.equal(resolveCity('北京市海淀區').id, '101010200');
assert.equal(resolveCity('北京市海淀区').label, '北京·海淀');
assert.throws(() => resolveCity('朝阳'), /同名/);
assert.throws(() => resolveCity('不存在的地方'), /未找到/);
const weather = parseCurrent(raw, resolveCity('海淀'), now);
assert.equal(weather.observedAt, '2026-10-22T10:10:00.000Z');
assert.equal(weather.temp, 14);
assert.equal(weather.wind, 8);
assert.equal(weather.source, '中国天气网');
assert.throws(() => parseCurrent(raw.replace('101010200', '101010100'), resolveCity('海淀'), now), /无效/);
assert.throws(() => parseCurrent(raw.replace('14.4', '999'), resolveCity('海淀'), now), /无效/);
assert.equal(observationTime({ date: '12月31日', time: '23:50' }, Date.parse('2027-01-01T00:10:00+08:00')), '2026-12-31T15:50:00.000Z');
assert.throws(() => observationTime({ date: '2月30日', time: '12:00' }, now), /无效/);
assert.deepEqual(parseForecast(forecast).map(day => day.date), ['2026-12-31', '2027-01-01', '2027-01-02', '2027-01-03']);
assert.equal(parseForecast(forecast)[0].tmax, null, 'Do not invent a missing daytime high');
assert.throws(() => parseForecast('<html>changed</html>'), /不可用/);
(async () => {
  let requests = 0, fail = false;
  const client = createWeatherClient({ now: () => now, fetchText: async url => { requests++; if (fail) throw new Error('天气连接超时，请重试'); return url.includes('sk_2d') ? raw : forecast; } });
  const first = await Promise.all([client.getWeather({ city: '海淀', force: true }), client.getWeather({ city: '海淀', force: true })]);
  assert.equal(requests, 2, 'Repeated refreshes must share one current/forecast request pair');
  assert.equal(first[0].cityId, first[1].cityId);
  await client.getWeather({ city: '北京市海淀区' });
  assert.equal(requests, 2, 'Automatic refresh respects the short cache');
  await client.getWeather({ city: '海淀', force: true });
  assert.equal(requests, 4, 'Manual refresh bypasses a completed cache');
  fail = true;
  await assert.rejects(client.getWeather({ city: '海淀', force: true }), /超时/);
  fail = false;
  assert.equal((await client.getWeather({ city: '海淀', force: true })).source, '中国天气网', 'A failed refresh must not block recovery');
  const partial = createWeatherClient({ now: () => now, fetchText: async url => { if (url.includes('sk_2d')) return raw; throw new Error('forecast unavailable'); } });
  assert.equal((await partial.getWeather({ city: '海淀' })).forecastNotice, '未来预报暂不可用');
  console.log('WEATHER_PASS: official city matching, simplified labels, duplicate refresh, force refresh, timeout recovery, observation date, month/year rollover, partial forecasts');
})().catch(error => { console.error(error); process.exitCode = 1; });
